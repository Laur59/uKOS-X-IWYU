/*
 * \brief aProcess_0
 *
 * - P0:  Configure the TensorFlow
 *        Configure the mlpn
 *        Every 1000-ms
 *          - Simple 3 layer MLP (1 hidden layers)
 *          - Display the result
 *
 */
namespace {

[[noreturn]]
void    aProcess_0([[maybe_unused]] const void *argument) {
            uint32_t    index, random;
    const   dataBase_t  *entry;

// Waiting for the prompt uKOS-X

    #ifdef PRINT_THE_RESULTS_S
    kern_suspendProcess(1000U);
    (void)dprintf(KSYST, "\n\n");
    #endif

    PRIVILEGE_ELEVATE;
    tfl::tfl_init();
    mlpn_init();

    while (true) {
        kern_suspendProcess(vSelectWait);
        led_toggle(KLED_1);

        random_read(KRANDOM_SOFT, &random, 1U);
        index = random % KNB_ENTRY;

        entry = &aTabEntry[index];
        ui_drawSmallImage(entry);

        tfl::tfl_classify(entry);
        mlpn_classify(entry);

        #ifdef PRINT_THE_RESULTS_S
        (void)dprintf(KSYST, "\n");
        #endif
    }
}
}

/*
 * \brief aProcess_1
 *
 * - P1:  Every 100-ms
 *          - Switch management
 *
 */
namespace {

[[noreturn]]
void    aProcess_1([[maybe_unused]] const void *argument) {
            uint32_t    button, oldButton = 0U, cpuPush = 1U;
    const   uint32_t    aWait[] = { 2000U, 1000U, 500U, 250U, 125U, 62U, 31U } ;

    PRIVILEGE_ELEVATE;
    while (true) {
        kern_suspendProcess(100U);

        switch_read(&button);
        if (button == 0U) {
            if (oldButton == 1U) {
                oldButton = 0U;
                vSelectWait = aWait[cpuPush];
                cpuPush++;
                cpuPush = cpuPush % 7U;
            }
        }
        else {
            oldButton = 1U;
        }
    }
}
}

